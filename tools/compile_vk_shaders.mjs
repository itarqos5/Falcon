// Compiles the Vulkan shaders (src/vulkan/shaders/*.vert, *.frag) to SPIR-V and writes them into src/vulkan/spirv_data.cpp as arrays, so that the game needs no shader compiler
// and the build needs none either. Run it after changing a shader and commit the result:
//
//   node tools/compile_vk_shaders.mjs [path of glslangValidator]
//
// glslangValidator comes with the Vulkan SDK, and as the package glslang-tools on Debian and Ubuntu. The Linux CI runs this and keeps the file it made as an artifact, which is
// how the file in the repository was made when no compiler was at hand on the development PC.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const shaderDir = path.join(root, 'src', 'vulkan', 'shaders');
const output = path.join(root, 'src', 'vulkan', 'spirv_data.cpp');
const compiler = process.argv[2] || 'glslangValidator';

const files = fs.readdirSync(shaderDir).filter((f) => /\.(vert|frag)$/.test(f)).sort();
if (files.length === 0) throw new Error('no shaders in ' + shaderDir);

const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'falcon-spv-'));
const arrays = [];
for (const file of files) {
  const spv = path.join(scratch, file + '.spv');
  try {
    execFileSync(compiler, ['-V', '--target-env', 'vulkan1.2', '-o', spv, path.join(shaderDir, file)], { stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (error) {
    process.stderr.write(`${file}: ${error.stdout || ''}${error.stderr || ''}\n`);
    process.exit(1);
  }
  const bytes = fs.readFileSync(spv);
  if (bytes.length % 4 !== 0) throw new Error(file + ': the SPIR-V is not a whole number of words');
  const words = [];
  for (let i = 0; i < bytes.length; i += 4) words.push('0x' + bytes.readUInt32LE(i).toString(16).padStart(8, '0'));
  arrays.push({ name: file, id: 'spv_' + file.replace('.', '_'), words });
}
fs.rmSync(scratch, { recursive: true, force: true });

let text = '// Generated by tools/compile_vk_shaders.mjs from src/vulkan/shaders/. Do not edit: change a shader and run the tool again.\n';
text += '#include "spirv_data.hpp"\n\nnamespace falcon::vulkan {\n\nnamespace {\n\n';
for (const a of arrays) {
  text += `const std::uint32_t ${a.id}[] = {\n`;
  for (let i = 0; i < a.words.length; i += 8) text += '    ' + a.words.slice(i, i + 8).join(', ') + ',\n';
  text += '};\n\n';
}
text += '}  // namespace\n\nconst SpirvBlob kSpirvBlobs[] = {\n';
for (const a of arrays) text += `    {"${a.name}", ${a.id}, sizeof(${a.id}) / sizeof(std::uint32_t)},\n`;
text += '};\nconst std::size_t kSpirvBlobCount = sizeof(kSpirvBlobs) / sizeof(kSpirvBlobs[0]);\n\n}  // namespace falcon::vulkan\n';
fs.writeFileSync(output, text);
console.log(`${arrays.length} shaders, ${arrays.reduce((n, a) => n + a.words.length * 4, 0)} bytes of SPIR-V -> ${path.relative(root, output)}`);
