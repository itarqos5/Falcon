// Writes the Items and Blocks classes of the platform from the names in the game's exported registries.json (names only: nothing else of the game's data is used):
//   node modapi/gen_registries.mjs <registries.json>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const registries = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));

const names = (key) => Object.keys(registries[key].entries).map((k) => k.replace(/^minecraft:/, '')).sort();
const constant = (name) => name.toUpperCase().replace(/[^A-Z0-9_]/g, '_');

function write(rel, text) {
  const file = path.join(here, 'src', rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

const items = names('minecraft:item');
write('net/minecraft/world/item/Items.java', `package net.minecraft.world.item;

import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;

// Generated by modapi/gen_registries.mjs from the names of the game's item registry.
public final class Items {
    private Items() {}

${items.map((n) => `    public static final Item ${constant(n)} = reg("${n}");`).join('\n')}

    private static Item reg(String name) {
        Item item = new Item(new Item.Properties());
        BuiltInRegistries.ITEM.add(Identifier.withDefaultNamespace(name), item);
        return item;
    }
}
`);

const blocks = names('minecraft:block');
write('net/minecraft/world/level/block/Blocks.java', `package net.minecraft.world.level.block;

import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;
import net.minecraft.world.level.block.state.BlockBehaviour;

// Generated by modapi/gen_registries.mjs from the names of the game's block registry.
public final class Blocks {
    private Blocks() {}

${blocks.map((n) => `    public static final Block ${constant(n)} = reg("${n}");`).join('\n')}

    private static Block reg(String name) {
        Block block = new Block(BlockBehaviour.Properties.of());
        BuiltInRegistries.BLOCK.add(Identifier.withDefaultNamespace(name), block);
        return block;
    }

    public static Block byName(String name) { return BuiltInRegistries.BLOCK.getValue(Identifier.parse(name)); }
}
`);
console.log(`${items.length} items, ${blocks.length} blocks`);
